"""Write frontend/js/demo-dictionary.js from data/*_classes.json, so the site's demo mode
(no server) can show the real list of signs the models know.

    python scripts/make_demo_dictionary.py      # run from backend/ after changing a classes file
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
OUT = HERE.parent / "frontend" / "js" / "demo-dictionary.js"
NO_SIGN = {"---"}

words = {}
for lang in ("rsl", "asl"):
    labels = json.loads((HERE / "data" / f"{lang}_classes.json").read_text(encoding="utf-8"))
    words[lang] = [w for w in labels if w not in NO_SIGN]

OUT.write_text(
    "// Generated by backend/scripts/make_demo_dictionary.py from backend/data/*_classes.json. Do not edit.\n"
    "export const DEMO_DICTIONARY = " + json.dumps(words, ensure_ascii=False, separators=(",", ":")) + ";\n",
    encoding="utf-8",
)
print(f"wrote {OUT} ({', '.join(f'{k}: {len(v)}' for k, v in words.items())})")
